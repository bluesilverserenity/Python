#a tuple is similar to a list but it is immutable, meaning that once it is created, it cannot be modified.

#creating a tuple
my_tuple = (1, 2, 3, "daniel")   #a tuple can contain different types of data
print(my_tuple)              #prints the entire tuple

#concatenating tuples
tuple1 = (1, 2, 3)  
tuple2 = ("a", "b", "c")
concatenated_tuple = tuple1 + tuple2  #concatenates tuple1 and tuple2
print(concatenated_tuple)    #prints the concatenated tuple 
